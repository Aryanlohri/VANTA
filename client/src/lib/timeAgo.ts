/**
 * Convert an ISO timestamp or Date to a human-readable relative time string.
 *
 * Examples: "just now", "3 minutes ago", "2 hours ago", "yesterday", "5 days ago"
 *
 * Zero dependencies — intentionally hand-rolled to avoid bloating the bundle
 * with a library like date-fns or dayjs for a single function.
 */
export function timeAgo(date: string | Date): string {
  const now = Date.now();
  const then = new Date(date).getTime();
  const seconds = Math.floor((now - then) / 1000);

  if (seconds < 60) return 'just now';

  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes}m ago`;

  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ago`;

  const days = Math.floor(hours / 24);
  if (days === 1) return 'yesterday';
  if (days < 30) return `${days}d ago`;

  const months = Math.floor(days / 30);
  if (months < 12) return `${months}mo ago`;

  const years = Math.floor(months / 12);
  return `${years}y ago`;
}
